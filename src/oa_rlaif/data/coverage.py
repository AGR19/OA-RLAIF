"""Per-file coverage of the raw data: every file gets exactly one role from configs/coverage.yaml.

`python -m oa_rlaif.data.coverage` scans OA_RAW_DIR (and OA_BIOML_DIR when present), writes
outputs/coverage/manifest.tsv (one row per file) and docs/COVERAGE.md (summary), and exits non-zero
if any file is unassigned. Derived-record counts are filled in later by the builders, and
data/verify.py fails if a data-bearing file ends with zero records.
"""

from __future__ import annotations

import re
import sys
from collections import Counter
from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path

from ..io import read_yaml, write_tsv
from ..paths import ROOT, bioml_dir, config_dir, out_dir, papers_dir, raw_dir

IGNORED_NAMES = {".DS_Store"}
# tool bookkeeping inside the data folders, not data: huggingface_hub's upload_large_folder writes .cache/huggingface/
IGNORED_DIRS = {(".cache", "huggingface")}


def glob_regex(pattern: str) -> re.Pattern:
    """POSIX-style glob: `**/` spans zero or more directories, `*` stays inside one path segment."""
    out, i = [], 0
    while i < len(pattern):
        if pattern.startswith("**/", i):
            out.append("(?:.*/)?")
            i += 3
        elif pattern.startswith("**", i):
            out.append(".*")
            i += 2
        elif pattern[i] == "*":
            out.append("[^/]*")
            i += 1
        elif pattern[i] == "?":
            out.append("[^/]")
            i += 1
        else:
            out.append(re.escape(pattern[i]))
            i += 1
    return re.compile("^" + "".join(out) + "$")


@dataclass(frozen=True)
class Rule:
    glob: str
    role: str
    family: str
    regex: re.Pattern


@lru_cache(maxsize=1)
def load_rules() -> tuple[tuple[Rule, ...], tuple[Rule, ...], frozenset[str]]:
    spec = read_yaml(config_dir() / "coverage.yaml")
    make = lambda items: tuple(Rule(r["glob"], r["role"], r["family"], glob_regex(r["glob"])) for r in items)  # noqa: E731
    return make(spec["rules"]), make(spec.get("bioml_rules", [])), frozenset(spec["data_bearing"])


@lru_cache(maxsize=1)
def papers_rules() -> tuple[Rule, ...]:
    spec = read_yaml(config_dir() / "coverage.yaml")
    return tuple(Rule(r["glob"], r["role"], r["family"], glob_regex(r["glob"])) for r in spec.get("papers_rules", []))


def classify(relative: str, rules) -> Rule | None:
    return next((rule for rule in rules if rule.regex.match(relative)), None)


def scan(root: Path, rules, source: str):
    for path in sorted(root.rglob("*")):
        if path.is_file() and path.name not in IGNORED_NAMES and not path.name.endswith(".partial"):
            if path.relative_to(root).parts[:2] in IGNORED_DIRS:
                continue
            relative = path.relative_to(root).as_posix()
            rule = classify(relative, rules)
            yield {
                "source": source,
                "path": relative,
                "bytes": path.stat().st_size,
                "role": rule.role if rule else "UNASSIGNED",
                "family": rule.family if rule else "",
                "rule": rule.glob if rule else "",
            }


def build_manifest() -> list[dict]:
    rules, bioml_rules, _ = load_rules()
    rows = list(scan(raw_dir(), rules, "raw"))
    if bioml_dir().exists():
        rows += list(scan(bioml_dir(), bioml_rules, "bioml"))
    if papers_dir().exists():
        rows += list(scan(papers_dir(), papers_rules(), "papers"))
    return rows


def summary_markdown(rows: list[dict]) -> str:
    _, _, data_bearing = load_rules()
    by_role = Counter(r["role"] for r in rows)
    by_family_role = Counter((r["source"], r["family"], r["role"]) for r in rows)
    size = Counter()
    for r in rows:
        size[r["role"]] += r["bytes"]
    unassigned = [r for r in rows if r["role"] == "UNASSIGNED"]
    raw_n = sum(r["source"] == "raw" for r in rows)
    lines = [
        "# Raw data coverage",
        "",
        f"Generated by `python -m oa_rlaif.data.coverage`. Files scanned: **{len(rows)}** "
        f"({raw_n} in `Raw Ontology Folders`, {len(rows) - raw_n} in the Bio-ML download). "
        f"Unassigned: **{len(unassigned)}**.",
        "",
        "Every file has exactly one role. Data-bearing roles must yield at least one derived record "
        "(checked by `data/verify.py` after the build); provenance files are recorded in the data card.",
        "",
        "| Role | Data-bearing | Files | Size (MB) |",
        "|---|---|---:|---:|",
    ]
    for role, count in sorted(by_role.items(), key=lambda x: -x[1]):
        lines.append(f"| {role} | {'yes' if role in data_bearing else 'no'} | {count} | {size[role] / 1e6:,.1f} |")
    lines += ["", "| Source | Family | Role | Files |", "|---|---|---|---:|"]
    for (source, family, role), count in sorted(by_family_role.items()):
        lines.append(f"| {source} | {family} | {role} | {count} |")
    if unassigned:
        lines += ["", "## Unassigned files", ""] + [f"- `{r['source']}:{r['path']}`" for r in unassigned[:200]]
    return "\n".join(lines) + "\n"


def main() -> int:
    rows = build_manifest()
    target = out_dir() / "coverage" / "manifest.tsv"
    write_tsv(target, ["source", "path", "bytes", "role", "family", "rule"], rows)
    (ROOT / "docs" / "COVERAGE.md").write_text(summary_markdown(rows))
    unassigned = sum(r["role"] == "UNASSIGNED" for r in rows)
    print(f"scanned {len(rows)} files; unassigned {unassigned}; manifest -> {target.relative_to(ROOT)}")
    return 1 if unassigned else 0


if __name__ == "__main__":
    sys.exit(main())
